"""Regenerate the checked-in presentation blit SPIR-V; no runtime compiler."""
import pathlib
import struct
import subprocess
import tempfile

directory = pathlib.Path(__file__).resolve().parent
output = ['/* SPDX-License-Identifier: MIT\n * Generated by shaders/generate.py. */\n',
          '#ifndef TGD3D_BLIT_SPV_H\n#define TGD3D_BLIT_SPV_H\n#include <stdint.h>\n']
with tempfile.TemporaryDirectory() as temporary:
    for stage in ('vert', 'frag'):
        binary = pathlib.Path(temporary) / (stage + '.spv')
        subprocess.run(['glslangValidator', '-V', '--target-env', 'vulkan1.1',
                        '-o', str(binary), str(directory / ('blit.' + stage))], check=True)
        subprocess.run(['spirv-val', '--target-env', 'vulkan1.1', str(binary)], check=True)
        code = binary.read_bytes()
        words = struct.unpack('<' + 'I' * (len(code) // 4), code)
        output.append('static const uint32_t tgd3d_blit_' + stage + '[] = {\n')
        for i in range(0, len(words), 8):
            output.append('   ' + ', '.join('0x%08x' % w for w in words[i:i+8]) + ',\n')
        output.append('};\n')
output.append('#endif\n')
(directory / 'blit_spv.h').write_text(''.join(output))
