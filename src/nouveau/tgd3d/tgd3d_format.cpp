const FormatInfo *format_info(DXGI_FORMAT format)
{
   static const auto lookup = [] {
      std::array<const FormatInfo *, 128> result = {};
      for (const auto &entry : table)
         result[entry.dxgi] = &entry.info;
      return result;
   }();
   return (unsigned)format < 128 ? lookup[format] : nullptr;
}

static bool is_depth_resource(const FormatInfo *info, UINT bind)
{
   return info->depth != VK_FORMAT_UNDEFINED &&
          ((bind & D3D10_DDI_BIND_DEPTH_STENCIL) || info->vk == VK_FORMAT_UNDEFINED ||
           (info->flags & (FMT_DEPTH | FMT_STENCIL)));
}

VkFormat resource_vk_format(const Device *dev, DXGI_FORMAT format, UINT bind)
{
   const FormatInfo *info = format_info(format);
   if (!info)
      return VK_FORMAT_UNDEFINED;
   if (is_depth_resource(info, bind))
      return info->depth;
   if ((info->flags & FMT_R_AS_ALPHA) && !dev->hasA8)
      return VK_FORMAT_R8_UNORM;
   return info->vk;
}

bool view_vk_format(const Device *dev, DXGI_FORMAT resource, UINT bind, DXGI_FORMAT view,
                    VkFormat *format, VkImageAspectFlags *aspect, VkComponentMapping *swizzle)
{
   const FormatInfo *ri = format_info(resource);
   const FormatInfo *vi = format_info(view);
   if (!ri || !vi || (vi->flags & (FMT_TYPELESS | FMT_NO_VIEW)))
      return false;
   /* A view reinterprets only within its typeless family. Fully typed 8-bit
    * RGBA/BGRA resources additionally accept their sRGB twin, which DXGI
    * uses for swap-chain buffers. */
   if (resource != view && (!ri->family || ri->family != vi->family))
      return false;
   *swizzle = {VK_COMPONENT_SWIZZLE_IDENTITY, VK_COMPONENT_SWIZZLE_IDENTITY,
               VK_COMPONENT_SWIZZLE_IDENTITY, VK_COMPONENT_SWIZZLE_IDENTITY};
   if (is_depth_resource(ri, bind)) {
      if (vi->depth != ri->depth)
         return false;
      *format = ri->depth;
      if ((vi->flags & FMT_DEPTH) && (vi->flags & FMT_STENCIL))
         *aspect = VK_IMAGE_ASPECT_DEPTH_BIT | VK_IMAGE_ASPECT_STENCIL_BIT;
      else if (vi->flags & FMT_STENCIL)
         *aspect = VK_IMAGE_ASPECT_STENCIL_BIT;
      else
         *aspect = VK_IMAGE_ASPECT_DEPTH_BIT;
      return true;
   }
   if (vi->vk == VK_FORMAT_UNDEFINED || (vi->flags & (FMT_DEPTH | FMT_STENCIL)))
      return false;
   *format = vi->vk;
   *aspect = VK_IMAGE_ASPECT_COLOR_BIT;
   if (vi->flags & FMT_ALPHA_ONE)
      swizzle->a = VK_COMPONENT_SWIZZLE_ONE;
   if ((vi->flags & FMT_R_AS_ALPHA) && !dev->hasA8) {
      *format = VK_FORMAT_R8_UNORM;
      *swizzle = {VK_COMPONENT_SWIZZLE_ZERO, VK_COMPONENT_SWIZZLE_ZERO,
                  VK_COMPONENT_SWIZZLE_ZERO, VK_COMPONENT_SWIZZLE_R};
   }
   return true;
}

VkFormat vertex_vk_format(DXGI_FORMAT format)
{
   const FormatInfo *info = format_info(format);
   if (!info || (info->flags & (FMT_TYPELESS | FMT_BC | FMT_DEPTH | FMT_STENCIL | FMT_NO_VIEW |
                                FMT_R_AS_ALPHA)))
      return VK_FORMAT_UNDEFINED;
   return info->vk;
}

uint32_t format_numeric_class(DXGI_FORMAT format)
{
   const FormatInfo *info = format_info(format);
   if (!info)
      return 0;
   return (info->flags & FMT_UINT) ? 1 : (info->flags & FMT_SINT) ? 2 : 0;
}

