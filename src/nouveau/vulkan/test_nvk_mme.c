#include "nvk_mme.h"

#include "nvk_cmd_buffer.h"
#include "nv_push.h"
#include "nv_push_cla097.h"
#include "nv_push_cla0c0.h"
#include "nv_push_clb197.h"
#include "nv_push_clb1c0.h"
#include "nv_push_clc397.h"
#include "nv_push_clc3c0.h"
#include "nv_push_clc597.h"
#include "nv_push_clc5c0.h"

#include <inttypes.h>
#include <stdio.h>
#include <string.h>

static const struct nv_device_info gm20b = {
   .type = NV_DEVICE_TYPE_SOC,
   .chipset = 0x12e,
   .sm = 53,
   .gpc_count = 1,
   .tpc_count = 2,
   .mp_per_tpc = 1,
   .cls_eng3d = MAXWELL_B,
   .cls_compute = MAXWELL_COMPUTE_B,
};

static int
emit_gm20b_windows_mme(void)
{
   uint32_t words[4096 + 1024];
   struct nv_push push;
   nv_push_init(&push, words, ARRAY_SIZE(words), BITFIELD_BIT(SUBC_NVB197));
   if (!nvk_push_mme_programs(&push, &gm20b, false))
      return 1;

   puts("/*\n"
        " * Copyright © 2022 Collabora Ltd. and Red Hat Inc.\n"
        " * SPDX-License-Identifier: MIT\n"
        " * Generated by test_nvk_mme --emit-gm20b-windows-mme.\n"
        " */\n"
        "#ifndef TG_GPU_NVK_MME_PROGRAMS_H\n"
        "#define TG_GPU_NVK_MME_PROGRAMS_H\n"
        "#include <stdint.h>\n");
   printf("#define TG_GPU_NVK_DRAW_CB0_BYTES %zuu\n",
          sizeof(struct nvk_root_descriptor_table));
   printf("#define TG_GPU_NVK_MME_CB0_ADDR_HI 0x%04xu\n",
          (unsigned)NVK_SET_MME_SCRATCH(CB0_ADDR_HI));
   printf("#define TG_GPU_NVK_MME_CB0_ADDR_LO 0x%04xu\n",
          (unsigned)NVK_SET_MME_SCRATCH(CB0_ADDR_LO));
   printf("#define TG_GPU_NVK_MME_ZERO_ADDR_HI 0x%04xu\n",
          (unsigned)NVK_SET_MME_SCRATCH(ZERO_ADDR_HI));
   printf("#define TG_GPU_NVK_MME_ZERO_ADDR_LO 0x%04xu\n\n",
          (unsigned)NVK_SET_MME_SCRATCH(ZERO_ADDR_LO));
   puts("static const uint32_t tg_gpu_nvk_mme_init[] = {");
   const size_t count = nv_push_dw_count(&push);
   for (size_t i = 0; i < count; i++) {
      if (i % 6 == 0)
         fputs("    ", stdout);
      printf("0x%08" PRIx32 "u,", words[i]);
      putchar(i % 6 == 5 || i + 1 == count ? '\n' : ' ');
   }
   puts("};\n\n#endif /* TG_GPU_NVK_MME_PROGRAMS_H */");
   return fflush(stdout) == 0 && !ferror(stdout) ? 0 : 1;
}

int main(int argc, char **argv)
{
   if (argc == 2 && strcmp(argv[1], "--emit-gm20b-windows-mme") == 0)
      return emit_gm20b_windows_mme();

   static const struct nv_device_info kepler = {
      .cls_eng3d = KEPLER_A,
      .cls_compute = KEPLER_COMPUTE_A,
   };
   static const struct nv_device_info volta = {
      .cls_eng3d = VOLTA_A,
      .cls_compute = VOLTA_COMPUTE_A,
   };
   static const struct nv_device_info turing = {
      .cls_eng3d = TURING_A,
      .cls_compute = TURING_COMPUTE_A,
   };

   nvk_test_all_mmes(&kepler);
   nvk_test_all_mmes(&gm20b);
   nvk_test_all_mmes(&volta);
   nvk_test_all_mmes(&turing);

   return 0;
}
